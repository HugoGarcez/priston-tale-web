"""Generate ptgfx\\ptgfx_stubs.h: a stub base class for every DirectDraw /
Direct3D 6 COM interface the game uses
(and ptsound\\ptsound_stubs.h for DirectSound).

Each PtStub_<Interface> derives from the real SDK interface and implements every
method: AddRef/Release do reference counting, everything else returns
E_NOTIMPL (or 0). The OpenGL implementation then only overrides the methods the
game actually calls.

Usage: python tools\\gen_ptgfx_stubs.py   (from the src folder)
"""
import re, os

SDK = r'C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\um'
# (output file, what it is for, headers -> interfaces)
TARGETS = [
    (os.path.join('ptgfx', 'ptgfx_stubs.h'), 'DirectDraw / Direct3D 6', 'OpenGL implementation (ptgfx)', {
        'ddraw.h': ['IDirectDraw4', 'IDirectDrawSurface4', 'IDirectDrawClipper'],
        'd3d.h':   ['IDirect3D3', 'IDirect3DDevice3', 'IDirect3DTexture2', 'IDirect3DViewport3'],
    }),
    (os.path.join('ptsound', 'ptsound_stubs.h'), 'DirectSound', 'SDL2 implementation (ptsound)', {
        'dsound.h': ['IDirectSound', 'IDirectSoundBuffer'],
    }),
]

method_re = re.compile(r'STDMETHOD(_\(\s*(?P<rtype>[^,]+?)\s*,\s*(?P<name1>\w+)\s*\)|\(\s*(?P<name2>\w+)\s*\))\s*\((?P<args>.*?)\)\s*PURE\s*;', re.S)

def parse(header, iface):
    text = open(os.path.join(SDK, header), encoding='latin-1').read()
    m = re.search(r'DECLARE_INTERFACE_\(\s*%s\s*,\s*\w+\s*\)\s*\{(.*?)\n\};' % iface, text, re.S)
    if not m:
        raise SystemExit('interface %s not found in %s' % (iface, header))
    methods = []
    for mm in method_re.finditer(m.group(1)):
        rtype = mm.group('rtype') or 'HRESULT'
        name = mm.group('name1') or mm.group('name2')
        args = ' '.join(mm.group('args').split())
        args = re.sub(r'^THIS_\s*', '', args)
        args = '' if args == 'THIS' else args
        # drop SAL annotations (_In_, _Out_opt_, _Outptr_result_bytebuffer_(n), ...): only
        # the Windows SDK knows them, and the web build uses the mingw headers
        args = re.sub(r'\b_(?:In|Out|Inout|Outptr|Pre|Post|Reserved|Deref|Ret|Field)[A-Za-z_]*_(?:\([^()]*(?:\([^()]*\))?[^()]*\))?\s*', '', args)
        methods.append((rtype.strip(), name, args))
    return methods

def generate(path, what, impl, wanted):
    out = ['// Generated by tools\\gen_ptgfx_stubs.py from the Windows SDK headers - do not edit.',
           '// Stub base classes for the %s interfaces: every method' % what,
           '// exists; the %s overrides the ones the game uses.' % impl,
           '#pragma once'] + ['#include <%s>' % h for h in wanted] + ['']
    for header, ifaces in wanted.items():
        for iface in ifaces:
            out.append('class PtStub_%s : public %s {' % (iface, iface))
            out.append('protected:')
            out.append('	LONG m_RefCount = 1;')
            out.append('public:')
            out.append('	virtual ~PtStub_%s() {}' % iface)
            for rtype, name, args in parse(header, iface):
                if name == 'AddRef':
                    body = '{ return InterlockedIncrement( &m_RefCount ); }'
                elif name == 'Release':
                    body = '{ LONG n = InterlockedDecrement( &m_RefCount ); if ( n==0 ) delete this; return n; }'
                elif name == 'QueryInterface':
                    args = 'REFIID riid, LPVOID *ppvObj'		# some SDK headers leave these unnamed
                    body = '{ if ( ppvObj ) *ppvObj = 0; return E_NOINTERFACE; }'
                elif rtype == 'HRESULT':
                    body = '{ return E_NOTIMPL; }'
                else:
                    body = '{ return 0; }'
                ret = 'HRESULT' if rtype == 'HRESULT' else rtype
                out.append('	STDMETHODIMP_(%s) %s( %s ) override %s' % (ret, name, args, body))
            out.append('};')
            out.append('')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write('\n'.join(out))
    print('wrote', path)

for target in TARGETS:
    generate(*target)
